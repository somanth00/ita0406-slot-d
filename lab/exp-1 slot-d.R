# Create Numeric Vector
a <- c(10, 20, 30, 40, 50)

# Create Character Vector
b <- c("Apple", "Mango", "Banana")

# Create Logical Vector
c <- c(TRUE, FALSE, TRUE)

# Display Values
cat("Numeric Vector:\n")
print(a)

cat("Character Vector:\n")
print(b)

cat("Logical Vector:\n")
print(c)

# Display Types
cat("Numeric Type:\n")
print(class(a))

cat("Character Type:\n")
print(class(b))

cat("Logical Type:\n")
print(class(c))
